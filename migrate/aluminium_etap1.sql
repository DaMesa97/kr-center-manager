-- Pozycje z JSON parsera (AluLpPosition bez warnings) → znormalizowane wiersze.
-- Nieznany construction_type → 'inne', ilość < 1 → 1, wymiary zaokrąglone do mm.
create or replace function public.import_alu_order__positions(p_positions jsonb)
 returns table(
   pos_no int, description text, construction_type text, system text,
   profile_color text, hardware_color text, fillings text,
   width_mm int, height_mm int, quantity int, weight_kg numeric, u_value numeric,
   notes jsonb, glass jsonb
 )
 language sql
 immutable
 set search_path to 'public'
as $function$
  select
    (p->>'pos_no')::int,
    coalesce(p->>'description', ''),
    case when p->>'construction_type' in ('drzwi', 'okno', 'scianka', 'inne')
         then p->>'construction_type' else 'inne' end,
    coalesce(p->>'system', ''),
    coalesce(p->>'profile_color', ''),
    coalesce(p->>'hardware_color', ''),
    coalesce(p->>'fillings', ''),
    round(nullif(p->>'width_mm', '')::numeric)::int,
    round(nullif(p->>'height_mm', '')::numeric)::int,
    greatest(coalesce(round(nullif(p->>'quantity', '')::numeric)::int, 1), 1),
    nullif(p->>'weight_kg', '')::numeric,
    nullif(p->>'u_value', '')::numeric,
    case when jsonb_typeof(p->'notes') = 'object' then p->'notes' else '{}'::jsonb end,
    case when jsonb_typeof(p->'glass') = 'array' then p->'glass' else '[]'::jsonb end
  from jsonb_array_elements(coalesce(p_positions, '[]'::jsonb)) p;
$function$;

revoke all on function public.import_alu_order__positions(jsonb) from public, anon;
grant execute on function public.import_alu_order__positions(jsonb) to authenticated, service_role;

-- Przycięcie etapów pozycji do nowej ilości sztuk (overwrite z mniejszą ilością):
-- done > quantity → done = quantity, marks obcięte do done (zdejmowane są
-- ostatnie kliknięcia — jak przy cofaniu). Etapy w normie zostają bez zmian.
create or replace function public.alu_trim_stages(p_stages jsonb, p_quantity int)
 returns jsonb
 language plpgsql
 immutable
 set search_path to 'public'
as $function$
declare
  v_out   jsonb := '{}'::jsonb;
  v_key   text;
  v_val   jsonb;
  v_done  int;
  v_marks jsonb;
begin
  if p_stages is null or jsonb_typeof(p_stages) <> 'object' then
    return '{}'::jsonb;
  end if;
  for v_key, v_val in select key, value from jsonb_each(p_stages) loop
    v_done := coalesce(nullif(v_val->>'done', '')::int, 0);
    if v_done > p_quantity then
      v_marks := case when jsonb_typeof(v_val->'marks') = 'array' then v_val->'marks' else '[]'::jsonb end;
      select coalesce(jsonb_agg(m.value order by m.ordinality), '[]'::jsonb)
      into v_marks
      from jsonb_array_elements(v_marks) with ordinality m
      where m.ordinality <= p_quantity;
      v_val := jsonb_build_object('done', p_quantity, 'marks', v_marks);
    end if;
    v_out := v_out || jsonb_build_object(v_key, v_val);
  end loop;
  return v_out;
end;
$function$;

revoke all on function public.alu_trim_stages(jsonb, int) from public, anon;
grant execute on function public.alu_trim_stages(jsonb, int) to authenticated, service_role;

create or replace function public.import_alu_order(p_header jsonb, p_positions jsonb, p_mode text default 'check')
 returns table(r_order_id bigint, r_result text, r_order_number text)
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_mode          text := coalesce(p_mode, 'check');
  v_order_number  text := trim(coalesce(p_header->>'order_number', ''));
  v_company       text := trim(coalesce(p_header->>'company', ''));
  v_realizacja    text := coalesce(nullif(p_header->>'realizacja', ''), 'wysylka');
  v_deadline      date;
  v_alu           jsonb;
  v_pos_count     int;
  v_pos_distinct  int;
  v_quantity      int;
  v_existing_id   bigint;
  v_order_id      bigint;
  v_new_number    text;
  v_suffix        int;
  v_entered_by    text;
begin
  perform public.assert_manager_or_service();

  if v_mode not in ('check', 'create', 'overwrite', 'duplicate') then
    raise exception 'Nieznany tryb importu: %', v_mode;
  end if;
  if v_order_number = '' then
    raise exception 'Brak numeru zlecenia (OF) w nagłówku listy produkcyjnej';
  end if;
  if v_realizacja not in ('wysylka', 'montaz') then
    raise exception 'Nieprawidłowa realizacja: % (dozwolone: wysylka, montaz)', v_realizacja;
  end if;
  if p_positions is null or jsonb_typeof(p_positions) <> 'array' or jsonb_array_length(p_positions) = 0 then
    raise exception 'Lista produkcyjna nie ma żadnych pozycji';
  end if;
  if exists (select 1 from jsonb_array_elements(p_positions) p where nullif(p->>'pos_no', '') is null) then
    raise exception 'Pozycja bez numeru (pos_no)';
  end if;

  select count(*), count(distinct n.pos_no), coalesce(sum(n.quantity), 0)
  into v_pos_count, v_pos_distinct, v_quantity
  from public.import_alu_order__positions(p_positions) n;
  if v_pos_count <> v_pos_distinct then
    raise exception 'Numery pozycji w liście produkcyjnej się powtarzają';
  end if;

  begin
    v_deadline := nullif(p_header->>'deadline', '')::date;
  exception when others then
    raise exception 'Nieprawidłowy termin: % (oczekiwano RRRR-MM-DD)', p_header->>'deadline';
  end;
  if v_deadline is null then
    raise exception 'Brak terminu realizacji (deadline)';
  end if;

  v_alu := jsonb_build_object(
    'lp_number',       coalesce(p_header->>'lp_number', ''),
    'lp_created_at',   nullif(p_header->>'lp_created_at', ''),
    'deadline',        to_char(v_deadline, 'YYYY-MM-DD'),
    'realizacja',      v_realizacja,
    'positions_count', coalesce(nullif(p_header->>'positions_count', '')::int, v_pos_count),
    'area_m2',         nullif(p_header->>'area_m2', '')::numeric,
    'weight_kg',       nullif(p_header->>'weight_kg', '')::numeric,
    'deadline_text',   coalesce(p_header->>'deadline_text', '')
  );

  -- „istniejące” = nieanulowane zlecenie Aluminium o tym numerze (wydane też się liczy)
  select o.id into v_existing_id
  from public.orders o
  where o.category = 'Aluminium'
    and o.order_number = v_order_number
    and coalesce((o.extra_fields->>'cancelled')::boolean, false) = false
  order by o.id desc
  limit 1;

  if v_mode = 'check' then
    if v_existing_id is not null then
      return query select v_existing_id, 'exists'::text, v_order_number;
      return;
    end if;
    v_mode := 'create';
  end if;

  -- ── overwrite ────────────────────────────────────────────────────────────
  if v_mode = 'overwrite' then
    if v_existing_id is null then
      raise exception 'Brak zlecenia % do nadpisania', v_order_number;
    end if;

    update public.orders o
    set company      = v_company,
        quantity     = v_quantity,
        extra_fields = coalesce(o.extra_fields, '{}'::jsonb) || jsonb_build_object('alu', v_alu)
    where o.id = v_existing_id;

    -- pozycje spoza nowego zestawu znikają (razem z etapami)
    delete from public.order_alu_positions ap
    where ap.order_id = v_existing_id
      and ap.pos_no not in (select n.pos_no from public.import_alu_order__positions(p_positions) n);

    -- obecne: update pól opisowych, etapy ZOSTAJĄ (przycięte do nowej ilości); nowe: insert
    insert into public.order_alu_positions (
      order_id, pos_no, description, construction_type, system, profile_color, hardware_color,
      fillings, width_mm, height_mm, quantity, weight_kg, u_value, notes, glass, production_stages
    )
    select v_existing_id, n.pos_no, n.description, n.construction_type, n.system, n.profile_color,
           n.hardware_color, n.fillings, n.width_mm, n.height_mm, n.quantity, n.weight_kg, n.u_value,
           n.notes, n.glass, '{}'::jsonb
    from public.import_alu_order__positions(p_positions) n
    on conflict (order_id, pos_no) do update set
      description       = excluded.description,
      construction_type = excluded.construction_type,
      system            = excluded.system,
      profile_color     = excluded.profile_color,
      hardware_color    = excluded.hardware_color,
      fillings          = excluded.fillings,
      width_mm          = excluded.width_mm,
      height_mm         = excluded.height_mm,
      quantity          = excluded.quantity,
      weight_kg         = excluded.weight_kg,
      u_value           = excluded.u_value,
      notes             = excluded.notes,
      glass             = excluded.glass,
      production_stages = public.alu_trim_stages(order_alu_positions.production_stages, excluded.quantity),
      updated_at        = now();

    return query select v_existing_id, 'overwritten'::text, v_order_number;
    return;
  end if;

  -- ── create / duplicate ───────────────────────────────────────────────────
  if v_mode = 'duplicate' then
    -- pierwszy wolny z serii „OF341/2026 (2)”, „(3)”… — unikalny indeks częściowy
    -- liczy też anulowane, więc sprawdzamy wszystkie zlecenia tej kategorii
    v_suffix := 2;
    loop
      v_new_number := v_order_number || ' (' || v_suffix || ')';
      exit when not exists (
        select 1 from public.orders o where o.category = 'Aluminium' and o.order_number = v_new_number
      );
      v_suffix := v_suffix + 1;
    end loop;
  else
    v_new_number := v_order_number;
    -- numer zajęty przez ANULOWANE zlecenie (check go nie widzi, ale indeks tak)
    if exists (select 1 from public.orders o where o.category = 'Aluminium' and o.order_number = v_new_number) then
      raise exception 'Zlecenie % już istnieje (anulowane) — zaimportuj jako duplikat', v_new_number;
    end if;
  end if;

  v_entered_by := coalesce(
    (select coalesce(nullif(pr.initials, ''), nullif(pr.full_name, ''))
     from public.profiles pr where pr.id = auth.uid()),
    'LP import'
  );

  insert into public.orders (
    category, order_number, company, order_date, quantity,
    production_day, sequence, notes, client_order_number,
    source, entered_by, production_stages, extra_fields
  ) values (
    'Aluminium', v_new_number, v_company, current_date, v_quantity,
    '', '', '', '',
    'alu_lp', v_entered_by, '{}'::jsonb, jsonb_build_object('alu', v_alu)
  )
  returning id into v_order_id;

  insert into public.order_alu_positions (
    order_id, pos_no, description, construction_type, system, profile_color, hardware_color,
    fillings, width_mm, height_mm, quantity, weight_kg, u_value, notes, glass, production_stages
  )
  select v_order_id, n.pos_no, n.description, n.construction_type, n.system, n.profile_color,
         n.hardware_color, n.fillings, n.width_mm, n.height_mm, n.quantity, n.weight_kg, n.u_value,
         n.notes, n.glass, '{}'::jsonb
  from public.import_alu_order__positions(p_positions) n;

  return query select v_order_id, 'created'::text, v_new_number;
end;
$function$;

revoke all on function public.import_alu_order(jsonb, jsonb, text) from public, anon;
grant execute on function public.import_alu_order(jsonb, jsonb, text) to authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- 5) Dopięcie dokumentu (PDF) do zlecenia — upsert po (order_id, kind)
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.attach_order_document(
  p_order_id bigint, p_kind text, p_number text, p_storage_path text, p_file_name text
)
 returns table(r_document_id bigint, r_replaced_storage_path text)
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_order_number text;
  v_old_path     text;
  v_doc_id       bigint;
  v_uploader     uuid;
begin
  perform public.assert_manager_or_service();

  if p_kind not in ('LP', 'LC') then
    raise exception 'Nieznany rodzaj dokumentu: % (dozwolone: LP, LC)', p_kind;
  end if;
  if coalesce(p_storage_path, '') = '' or coalesce(p_file_name, '') = '' then
    raise exception 'Brak ścieżki lub nazwy pliku dokumentu';
  end if;

  select o.order_number into v_order_number from public.orders o where o.id = p_order_id;
  if not found then
    raise exception 'Zlecenie % nie istnieje', p_order_id;
  end if;

  select d.storage_path into v_old_path
  from public.order_documents d
  where d.order_id = p_order_id and d.kind = p_kind;

  -- service_role nie ma profilu — uploaded_by zostaje puste
  select pr.id into v_uploader from public.profiles pr where pr.id = auth.uid();

  insert into public.order_documents (order_id, order_number, kind, number, storage_path, file_name, uploaded_by, uploaded_at)
  values (p_order_id, v_order_number, p_kind, nullif(trim(p_number), ''), p_storage_path, p_file_name, v_uploader, now())
  on conflict (order_id, kind) do update set
    order_number = excluded.order_number,
    number       = excluded.number,
    storage_path = excluded.storage_path,
    file_name    = excluded.file_name,
    uploaded_by  = excluded.uploaded_by,
    uploaded_at  = now()
  returning id into v_doc_id;

  return query select
    v_doc_id,
    case when v_old_path is not null and v_old_path <> p_storage_path then v_old_path else null end;
end;
$function$;

revoke all on function public.attach_order_document(bigint, text, text, text, text) from public, anon;
grant execute on function public.attach_order_document(bigint, text, text, text, text) to authenticated, service_role;

-- ─────────────────────────────────────────────────────────────────────────────
-- 6) Szukanie zlecenia Aluminium po numerze OF (dopinanie listy cięcia)
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.find_alu_order(p_order_number text)
 returns table(r_order_id bigint, r_order_number text, r_company text, r_release_date date)
 language sql
 stable
 security definer
 set search_path to 'public'
as $function$
  select o.id, o.order_number, o.company, o.release_date
  from public.orders o
  where o.category = 'Aluminium'
    and length(trim(coalesce(p_order_number, ''))) > 0
    and left(o.order_number, length(trim(p_order_number))) = trim(p_order_number)
    and (
      length(o.order_number) = length(trim(p_order_number))
      or substr(o.order_number, length(trim(p_order_number)) + 1) ~ '^ \(\d+\)$'
    )
    and coalesce((o.extra_fields->>'cancelled')::boolean, false) = false
  order by o.id desc;
$function$;

revoke all on function public.find_alu_order(text) from public, anon;
grant execute on function public.find_alu_order(text) to authenticated, service_role;
