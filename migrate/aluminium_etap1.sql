-- 2026-10-23: Stolarka aluminiowa — etap 1 (baza).
--
-- Nowa kategoria zleceń „Stolarka aluminiowa” (w bazie category = 'Aluminium').
-- Zlecenie = lista produkcyjna (LP) z AluronCAD: numer zlecenia = numer OF
-- (np. OF341/2026), nagłówek LP w orders.extra_fields.alu, konstrukcje (do 100)
-- w osobnej tabeli order_alu_positions z etapami PER POZYCJA i PER SZTUKA
-- (production_stages = { etap: { done, marks[] } }, sztuka = klik).
-- PDF-y (LP + lista cięcia LC) lądują w PRYWATNYM buckecie order-documents,
-- metadane w order_documents (jeden LP i jedna LC na zlecenie — nowy plik
-- zastępuje stary, klient kasuje poprzednią ścieżkę ze storage).
--
-- 1) order_alu_positions — pozycje LP; RLS: odczyt zalogowani, zapis kierownik
--    (zapisy i tak idą przez RPC). Realtime + REPLICA IDENTITY FULL pod etap 2.
-- 2) order_documents — metadane PDF-ów; order_number to snapshot do odnalezienia
--    pliku po archiwizacji zlecenia (order_id ON DELETE SET NULL).
-- 3) bucket order-documents (prywatny, 20 MB, tylko PDF) + polityki storage.objects
--    (wzór: order_photos_*; odczyt zalogowani, zapis/zmiana/usunięcie kierownik).
-- 4) import_alu_order(header, positions, mode) — jedna transakcja: zlecenie +
--    pozycje. Tryby: check (istnieje → 'exists', nic nie zmienia; nie → create),
--    create, overwrite (merge extra_fields.alu, pozycje: update/insert/delete,
--    etapy zostają z przycięciem done do nowej ilości), duplicate (numer z
--    sufiksem „ (2)”, „ (3)”… — respektuje unikalny indeks częściowy
--    orders_unique_number_per_category_new na (category, order_number)).
-- 5) attach_order_document — upsert po (order_id, kind); zwraca poprzednią ścieżkę.
-- 6) find_alu_order — do dopinania listy cięcia: nieanulowane zlecenia Aluminium
--    o danym numerze OF (także z sufiksem „ (n)”), najnowsze pierwsze.
-- Wszystkie RPC: SECURITY DEFINER z własnym guardem (assert_manager_or_service),
-- REVOKE FROM PUBLIC, anon + GRANT TO authenticated, service_role.

